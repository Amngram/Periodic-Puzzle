/* عنصرهای درسی هر مرحله را به‌صورت تجمعی محاسبه می‌کند */
function computeCumulativeQuiz(regionIdx, levelIdx) {
    const nums = new Set();
    for (let r = 0; r <= regionIdx; r++) {
        const levels = RAW_REGIONS[r].lv;
        const lastLevel = (r < regionIdx) ? levels.length - 1 : levelIdx - 1;
        for (let l = 0; l <= lastLevel; l++) {
            levels[l][2].forEach(n => nums.add(n));
        }
    }
    return Array.from(nums).sort((a, b) => a - b);
}

